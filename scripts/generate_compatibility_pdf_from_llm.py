def _slugify(model: str) -> str:
    """sonnet-4.6-medium → sonnet-4.6-medium (оставляем как есть, просто sanitize)."""
    return re.sub(r"[^\w.\-]", "_", model)


def main() -> None:
    parser = argparse.ArgumentParser(description="Сгенерировать PDF синастрии из LLM-ответа")
    parser.add_argument(
        "--model",
        default="sonnet-4.6-medium",
        help="Название модели (попадёт в имя файла)",
    )
    parser.add_argument(
        "--json",
        default=None,
        metavar="FILE",
        help="Путь к JSON-файлу с LLM-ответом (иначе встроенный ответ для --model)",
    )
    parser.add_argument(
        "--output-dir",
        default="docs/output",
        help="Папка для сохранения PDF",
    )
    parser.add_argument(
        "--bot-username",
        default=None,
        help="Telegram username для CTA",
    )
    args = parser.parse_args()

    # --- Загрузить JSON ---
    if args.json:
        raw = Path(args.json).read_text(encoding="utf-8")
    elif args.model in _EMBEDDED_RESPONSES:
        raw = _EMBEDDED_RESPONSES[args.model]
    else:
        available = ", ".join(_EMBEDDED_RESPONSES) or "нет"
        raise SystemExit(
            f"Нет встроенного ответа для модели '{args.model}'.\n"
            f"Передай --json path/to/response.json или добавь ответ в _EMBEDDED_RESPONSES.\n"
            f"Встроенные: {available}"
        )

    llm_output = CompatibilityLlmOutput.model_validate(json.loads(raw))

    # --- Натальные данные пары ---
    prompt_input = build_aidamir_angela_prompt_input()

    # --- Маппинг → PDF-модель ---
    report = llm_output_to_report_data(prompt_input, llm_output)

    # --- Имя файла: синастрия_персоны_модель_дата.pdf ---
    slug = _slugify(args.model)
    ts = datetime.now().strftime("%Y%m%d_%H%M%S")
    name_a = prompt_input.person_a.name.lower()
    name_b = prompt_input.person_b.name.lower()
    filename = f"synastry_{name_a}_{name_b}_{slug}_{ts}.pdf"
    output_path = Path(args.output_dir) / filename

    path = generate_synastry_pdf(output_path, report, bot_username=args.bot_username)
    print("PDF created:", path)


if __name__ == "__main__":
    main()
