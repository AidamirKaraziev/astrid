def build_prototype_report() -> SynastryReportData:
    """Прототип v2: история пары + живые тексты для превью PDF."""
    base = build_sample_report()
    return SynastryReportData(
        person_a=base.person_a,
        person_b=base.person_b,
        tldr=(
            "Между вами работает редкая связка: он зажигает её действием, она отвечает теплом — "
            "и это чувствуется с первых встреч. Сложность не в притяжении, а в быту: "
            "разный ритм Лун просит переводчика, а не победителя."
        ),
        natal_insight=(
            "Воздух + огонь: союз идей и движения. Его Водолей ищет смысл и свободу, "
            "её Стрелец — горизонт и честность. Луна Дева ↔ Близнецы: разный быт, "
            "но общий запрос на ясность — если договориться о правилах дома, конфликт сходит на нет."
        ),
        metrics=base.metrics,
        strong_aspects=base.strong_aspects,
        working_aspects=base.working_aspects,
        zone_blocks=base.zone_blocks,
        conclusion_quote=(
            "Ваша химия не требует доказательств — она уже есть. Задача не «создать любовь», "
            "а научиться говорить на двух эмоциональных языках одновременно: его прямоте "
            "и её потребности в пространстве для чувств."
        ),
        conclusion_tip=(
            "В пятницу вечером каждый пишет на бумажке одну фразу: "
            "«Сегодня я почувствовал(а), что меня любят, когда…» — и читаете вслух без комментариев."
        ),
        pair_story=(
            "Вы встречаетесь на стыке идей и чувств. Айдамир приносит импульс — "
            "желание двигаться, пробовать, не застревать в рутине. Анжела отвечает живостью "
            "и эмоциональной гибкостью: рядом с ним легче рискнуть, а рядом с ней — "
            "не потерять контакт с собой.\n\n"
            "В конфликте это выглядит так: он хочет решить вопрос сразу, она — сначала понять, "
            "что каждый чувствует. Это не «кто прав», а разные скорости. Когда вы называете это вслух, "
            "спор превращается в договор, а не в борьбу за контроль.\n\n"
            "Сильная сторона пары — вы не гасите друг друга. Даже напряжённые аспекты здесь "
            "про рост: один учится терпению, другой — прямоте. Если держать фокус на конкретике "
            "«что мне нужно сейчас», а не на обвинениях, связь становится глубже с каждым циклом."
        ),
        read_time_label="~6–7 мин чтения",
    )
