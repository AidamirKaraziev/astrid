# Советские названия. Первой строкой их не требуем — и вот почему: посёлки
# «Ленинград» в Туркменистане и «Куйбышев» в Оренбургской области существуют
# до сих пор, и по правилу «сначала совпадение» они честно выигрывают у
# Петербурга и Самары, для которых это лишь бывшее имя.
#
# Требуем другого, того, что человек реально делает: чтобы **регион нужного
# города оказался среди предложенных на первом шаге**. Тогда родившийся до
# девяносто первого выбирает свою область и находит город.
#
# (запрос, регион, который обязан быть в списке)
HISTORIC_REGIONS: tuple[tuple[str, str], ...] = (
    ("Ленинград", "Санкт-Петербург"),
    ("Свердловск", "Свердловская область"),
    ("Горький", "Нижегородская область"),
    ("Куйбышев", "Самарская область"),
)


async def verify_catalog(session) -> list[str]:  # noqa: ANN001 — AsyncSession, без импорта ради лёгкости модуля
    """Прогнать контрольный список по живому справочнику.

    Возвращает список человекочитаемых провалов; пустой список — всё в порядке.

    Зовётся из `scripts/import_geonames.py` сразу после импорта: это
    единственный момент, когда проверка точно нужна и точно возможна. В CI
    справочника нет (качать 200 МБ на каждый прогон незачем), а на машине
    разработчика и на сервере — есть.
    """
    from astra.places import crud

    failures: list[str] = []

    for query, name, country in ALL_CASES:
        found = await crud.search_places(session, query, limit=1)
        if not found:
            failures.append(f"«{query}» не находится вовсе")
            continue
        best = found[0]
        if (best.name, best.country_name) != (name, country):
            failures.append(f"«{query}» → {best.display_name}, ждали «{name}, {country}»")

    for query, region in HISTORIC_REGIONS:
        search = await crud.prepare_search(session, query)
        if search is None:
            failures.append(f"«{query}» не находится вовсе")
            continue
        regions = await crud.regions_for(session, search, limit=8)
        if region not in [hit.admin1_name for hit in regions]:
            failures.append(f"«{query}» не предлагает регион «{region}»")

    return failures
