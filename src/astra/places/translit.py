"""Кириллица ↔ латиница для поиска мест.

Зачем это здесь, а не «просто ищем по названию».

У четверти населённых пунктов СНГ русского имени в GeoNames нет вообще:
деревня Зябриково лежит там как `Zyabrikovo`, и всё. Выдумывать ей русское
написание нельзя — машинная транслитерация регулярно врёт («Сокал» вместо
«Сокола»), а орфографическая ошибка в месте рождения человека недопустима.

Поэтому транслитерируем **не данные, а запрос**. Человек пишет «Зябриково»,
мы про себя получаем `zyabrikovo` и находим латинскую запись; на кнопке он
видит ровно то написание, которое лежит в источнике. Ни одного придуманного
названия.

Второе применение — выбор синонима на импорте. У GeoNames в куче синонимов
может лежать и «Сокол», и белорусский «Сокал». Правильный тот, чья
транслитерация совпадает с латинским написанием из того же источника.

Таблица повторяет романизацию BGN/PCGN — именно ей GeoNames пишет колонку
`asciiname`, так что `Жуково` → `zhukovo` совпадает с их `Zhukovo`.
"""

from __future__ import annotations

import unicodedata

# Кириллица → латиница. Больше одной буквы дают шипящие: щ → shch.
_TO_LATIN = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
    "ж": "zh", "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "kh", "ц": "ts", "ч": "ch", "ш": "sh", "щ": "shch",
    "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
    # Украинский, белорусский и языки Средней Азии и Кавказа: у мест СНГ
    # эти буквы встречаются в названиях наравне с русскими.
    # Буквы с диакритикой (ӑ, ӗ, ў, ғ) сюда не попадают: `fold` снимает
    # надстрочные знаки раньше, и до таблицы доходит базовая буква.
    "і": "i", "ї": "yi", "є": "ye", "ґ": "g",
    "ә": "a", "қ": "k", "ң": "n", "ө": "o", "ұ": "u", "ү": "u",
    "һ": "h", "ҳ": "h", "ҷ": "j", "ҫ": "s", "ҙ": "z", "ҡ": "k",
}

# Латиница → кириллица. Порядок важен: длинные сочетания разбираются первыми,
# иначе «sh» распадётся на «с» и «х».
_TO_CYRILLIC = [
    ("shch", "щ"), ("zh", "ж"), ("kh", "х"), ("ts", "ц"), ("ch", "ч"),
    ("sh", "ш"), ("yu", "ю"), ("ya", "я"), ("yo", "ё"), ("ye", "е"),
    ("a", "а"), ("b", "б"), ("v", "в"), ("g", "г"), ("d", "д"), ("e", "е"),
    ("z", "з"), ("i", "и"), ("y", "й"), ("k", "к"), ("l", "л"), ("m", "м"),
    ("n", "н"), ("o", "о"), ("p", "п"), ("r", "р"), ("s", "с"), ("t", "т"),
    ("u", "у"), ("f", "ф"), ("h", "х"), ("c", "к"), ("j", "й"), ("q", "к"),
    ("w", "в"), ("x", "кс"),
]

_CYRILLIC_RANGE = ("Ѐ", "ӿ")

# Буквы, у которых знак вписан в саму букву, а не стоит над ней: NFD их не
# разбирает, и без этой таблицы `Sokoł` не совпадёт с `Sokol`.
_STROKED = str.maketrans(
    {"ł": "l", "đ": "d", "ð": "d", "ø": "o", "ħ": "h", "ŧ": "t", "ı": "i",
     "æ": "ae", "œ": "oe", "ß": "ss", "þ": "th"},
)


def has_cyrillic(text: str) -> bool:
    return any(_CYRILLIC_RANGE[0] <= char <= _CYRILLIC_RANGE[1] for char in text)


def fold(text: str) -> str:
    """Единый вид для сравнения: без диакритики, регистра и знаков.

    Снимаем именно диакритику, а не всё подряд: в источнике попадаются
    `Sokoł`, `Ярослáвичи` и прочие следы чужих раскладок, и без этого они
    не совпадут сами с собой.
    """
    decomposed = unicodedata.normalize("NFD", text.lower().translate(_STROKED))
    stripped = "".join(ch for ch in decomposed if unicodedata.category(ch) != "Mn")
    return "".join(ch for ch in stripped if ch.isalnum() or ch.isspace()).strip()


def to_latin(text: str) -> str:
    """«Жуково» → `zhukovo`. Латинские буквы проходят насквозь."""
    out: list[str] = []
    for char in fold(text):
        out.append(_TO_LATIN.get(char, char))
    return " ".join("".join(out).split())


def to_cyrillic(text: str) -> str:
    """`Zhukovo` → «жуково». Обратная сторона: человек пишет латиницей."""
    source = fold(text)
    out: list[str] = []
    position = 0
    while position < len(source):
        for latin, cyrillic in _TO_CYRILLIC:
            if source.startswith(latin, position):
                out.append(cyrillic)
                position += len(latin)
                break
        else:
            out.append(source[position])
            position += 1
    return " ".join("".join(out).split())


def latin_key(text: str) -> str:
    """Ключ сравнения независимо от алфавита: и «Жуково», и `Zhukovo` → `zhukovo`.

    Сравнивать всё в латинице, а не в кириллице, потому что латиница —
    единственный алфавит, в котором в источнике записано **каждое** место.
    """
    return to_latin(text) if has_cyrillic(text) else fold(text)
